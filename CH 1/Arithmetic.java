public class Arithmetic {
    public static void maths() {
        int a = 5+5;
        double b = 5.1-3.3;
        int c = 3*4;
        double s = Math.pow(4,2);
        
        System.out.println("5+5 = " + a);
        System.out.println("5.1-3.3 = " + b);
        System.out.println("3*4 = " + c);
        System.out.println("4 squared = " + s);
    }

    public static void main(String[] args) {
        maths();
    }
    
}
